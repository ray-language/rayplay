# Extracts the AAC tables of ISO/IEC 14496-3 (Huffman codebooks, scale factor bands, TNS limits)
# from FFmpeg's libavcodec/aactab.c into a raylang module, with the Huffman codes turned into
# two-level lookup tables.
#   python3 scripts/aactables.py aactab.c > src/aac_tables.ray && ray fmt --write src/aac_tables.ray
import re, sys
src = open(sys.argv[1]).read()

def arr(name):
    m = re.search(r'\b' + re.escape(name) + r'\s*\[[^\]]*\]\s*=\s*\{', src)
    assert m, name
    body = src[m.end():src.index('}', m.end())]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [int(t.strip(), 0) for t in body.split(',') if t.strip()]

# Primary table bits; longer codes go to a second table indexed by the bits that follow.
P = 9

def lookup(codes, lens):
    """Entry >= 0: symbol << 5 | length. Entry < 0: -(offset << 5 | bits) of a second-level
    table indexed by the `bits` after the first P. Unused entries decode as symbol 0, length P."""
    t = [P] * (1 << P)
    long_by_prefix = {}
    for sym, (c, n) in enumerate(zip(codes, lens)):
        if n <= P:
            base = c << (P - n)
            for k in range(1 << (P - n)):
                t[base + k] = sym << 5 | n
        else:
            long_by_prefix.setdefault(c >> (n - P), []).append((sym, c, n))
    for prefix, items in sorted(long_by_prefix.items()):
        bits = max(n for _, _, n in items) - P
        offset = len(t)
        t[prefix] = -(offset << 5 | bits)
        sub = [P + bits] * (1 << bits)
        for sym, c, n in items:
            rest = c & ((1 << (n - P)) - 1)
            base = rest << (bits - (n - P))
            for k in range(1 << (bits - (n - P))):
                sub[base + k] = sym << 5 | n
        t += sub
    # Self-check: every code decodes to its symbol.
    for sym, (c, n) in enumerate(zip(codes, lens)):
        w = c << (24 - n)
        e = t[w >> (24 - P)]
        if e < 0:
            off, bits = (-e) >> 5, (-e) & 31
            e = t[off + ((w >> (24 - P - bits)) & ((1 << bits) - 1))]
        assert e >> 5 == sym and e & 31 == n, (sym, c, n, e)
    return t

def fmt(vals, per=12):
    return '\n'.join('        ' + ', '.join(str(v) for v in vals[k:k + per]) + ','
                     for k in range(0, len(vals), per))

def fn(name, vals, doc):
    return f'/// {doc}\npub fn {name}() -> [int] {{\n    [\n{fmt(vals)}\n    ]\n}}\n'

def rows(name, rs, doc):
    body = '\n'.join('        [' + ', '.join(str(v) for v in r) + '],' for r in rs)
    return f'/// {doc}\npub fn {name}() -> [[int]] {{\n    [\n{body}\n    ]\n}}\n'

out = ['// AAC tables of ISO/IEC 14496-3, generated by scripts/aactables.py from FFmpeg\'s',
       '// libavcodec/aactab.c. The Huffman codebooks are two-level lookup tables: index the first with',
       f'// the next {P} bits; an entry >= 0 is symbol << 5 | code length, and one < 0 is',
       f'// -(offset << 5 | bits) of a second-level table indexed by the `bits` after those {P}.',
       '// The decoder calls each function once and keeps the arrays.', '']
out.append(f'pub const PRIMARY_BITS: int = {P};\n')
sf = lookup(arr('ff_aac_scalefactor_code'), arr('ff_aac_scalefactor_bits'))
assert len(sf) < 2000, len(sf)
out.append(fn('scalefactor', sf,
              'The scale factor codebook: symbols 0..120 are differences of -60..60.'))
# One function per codebook: the native backend cannot compile an array literal of more than
# about 2500 elements (rustc dies with SIGBUS, ray-apps finding #164), so `spectral()` joins
# them at run time.
index, at = [], 0
for k in range(1, 12):
    index.append(at)
    t = lookup(arr(f'codes{k}'), arr(f'bits{k}'))
    # Second-level offsets count from the start of the joined table.
    t = [e if e >= 0 else -(((-e >> 5) + at) << 5 | (-e & 31)) for e in t]
    assert len(t) < 2000, (k, len(t))
    out.append(fn(f'spectral_{k}', t, f'Spectral codebook {k}.'))
    at += len(t)
joined = ' + '.join(f'spectral_{k}()' for k in range(1, 12))
out.append(f'/// The 11 spectral codebooks, one after another.\npub fn spectral() -> [int] {{\n    {joined}\n}}\n')
out.append(fn('spectral_index', index, 'Where each spectral codebook (1..11) starts in `spectral()`.'))

def offsets(name):
    m = re.search(r'\b' + re.escape(name) + r'\s*\[\]\s*=\s*\{(.*?)\}', src, re.S)
    names = [t.strip() for t in m.group(1).split(',') if t.strip()]
    names = [re.sub(r'/\*.*?\*/', '', n, flags=re.S).strip() for n in names]
    return [arr(n) for n in names]

out.append(rows('swb_long', offsets('ff_swb_offset_1024'),
                'Scale factor band offsets of a long window, per sampling frequency index.'))
out.append(rows('swb_short', offsets('ff_swb_offset_128'),
                'Scale factor band offsets of a short window, per sampling frequency index.'))
out.append(fn('tns_max_long', arr('ff_tns_max_bands_1024'), 'Bands TNS may reach in a long window (LC).'))
out.append(fn('tns_max_short', arr('ff_tns_max_bands_128'), 'Bands TNS may reach in a short window (LC).'))
print('\n'.join(out), end='')
