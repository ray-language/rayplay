# Extracts the Layer III tables from minimp3.h (CC0) into a raylang module.
import re, sys
src = open(sys.argv[1]).read()

def arr(name):
    m = re.search(r'\b' + re.escape(name) + r'\s*(\[[^\]]*\])+\s*=\s*\{', src)
    assert m, name
    i = m.end(); depth = 1
    while depth:
        c = src[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    body = src[m.end():i - 1]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [t.strip() for t in body.replace('{', ',').replace('}', ',').split(',') if t.strip()]

def ints(name):
    return [int(t) for t in arr(name)]

def floats(name):
    out = []
    for t in arr(name):
        t = t.rstrip('f')
        v = float(t)
        out.append(repr(v) if '.' in repr(v) and 'e' not in repr(v) else ('%.10f' % v).rstrip('0').rstrip('.') + ('' if '.' in ('%.10f' % v).rstrip('0') else '.0'))
    return out

def fmt(vals, per=12):
    lines = []
    for k in range(0, len(vals), per):
        lines.append('        ' + ', '.join(vals[k:k + per]) + ',')
    return '\n'.join(lines)

def fn6(name, ty, vals, doc):
    body = '\n'.join('        ' + ', '.join(vals[k:k + 6]) + ',' for k in range(0, len(vals), 6))
    return f'/// {doc}\npub fn {name}() -> [{ty}] {{\n    [\n{body}\n    ]\n}}\n'

def fn(name, ty, vals, doc):
    return f'/// {doc}\npub fn {name}() -> [{ty}] {{\n    [\n{fmt(vals)}\n    ]\n}}\n'

out = ['// Layer III tables, generated by scripts/mp3tables.py from minimp3.h',
       '// (https://github.com/lieff/minimp3, CC0 / public domain). Functions, not `const`s: indexing a',
       '// `const` array rebuilds it on every access (findings #157), so the decoder calls each one once.', '']
out.append(fn('huffman', 'int', [str(v) for v in ints('tabs')], 'The big-value Huffman codebooks, all in one array (minimp3 `tabs`).'))
out.append(fn('huffman_index', 'int', [str(v) for v in ints('tabindex')], 'Where each of the 32 codebooks starts in `huffman()`.'))
out.append(fn('linbits', 'int', [str(v) for v in ints('g_linbits')], 'Extra bits of each codebook for values of 15 and up.'))
out.append(fn('count1_a', 'int', [str(v) for v in ints('tab32')], 'Count-1 codebook A (quadruples).'))
out.append(fn('count1_b', 'int', [str(v) for v in ints('tab33')], 'Count-1 codebook B.'))
for nm, doc in (('g_scf_long', 'Long-block scale factor band widths, 8 sample-rate rows of 23 (0-terminated).'),
                ('g_scf_short', 'Short-block band widths, 8 rows of 40 (each band thrice, 0-terminated).'),
                ('g_scf_mixed', 'Mixed-block band widths, 8 rows of 40 (0-terminated).')):
    vals = ints(nm)
    width = 23 if nm == 'g_scf_long' else 40
    # g_scf_mixed rows are shorter in the C source; pad each row to its declared width.
    rows = []
    body = src[src.index(nm):]
    body = body[body.index('{') + 1:]
    for row in re.findall(r'\{([^{}]*)\}', body[:body.index('};')]):
        r = [int(x) for x in row.split(',') if x.strip()]
        rows += r + [0] * (width - len(r))
    out.append(fn(nm[2:], 'int', [str(v) for v in rows], doc))
out.append(fn('scf_partitions', 'int', [str(v) for v in ints('g_scf_partitions')], 'MPEG-2 scale factor partitions, 3 rows of 28.'))
out.append(fn6('pow43', 'float', floats('g_pow43'), 'x^(4/3) for x in -15..=128 (index 16 + x; the first 16 are the negatives).'))
out.append(fn6('synth_window', 'float', floats('g_win'), 'The polyphase synthesis window, as minimp3 orders it.'))
open(sys.argv[2], 'w').write('\n'.join(out))
